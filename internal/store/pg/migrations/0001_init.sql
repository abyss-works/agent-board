-- 7. graph_edge
CREATE TABLE graph_edge (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id             BIGINT NOT NULL REFERENCES project(id),
    source_type            TEXT NOT NULL CHECK (source_type IN ('issue', 'spec', 'record', 'epic')),
    source_id              BIGINT NOT NULL,
    target_type            TEXT CHECK (target_type IS NULL OR target_type IN ('issue', 'spec', 'record', 'epic')),
    target_id              BIGINT,
    unresolved_target_text TEXT,
    kind                   TEXT NOT NULL CHECK (kind IN ('supersedes', 'about', 'depends_on', 'related')),
    origin                 TEXT NOT NULL CHECK (origin IN ('explicit', 'inferred')),
    status                 TEXT NOT NULL CHECK (status IN ('confirmed', 'candidate', 'rejected', 'removed')),
    confidence             DOUBLE PRECISION CHECK (confidence IS NULL OR (confidence >= 0.0 AND confidence <= 1.0)),
    evidence               TEXT,
    decided_by             TEXT REFERENCES actor(id),
    decided_at             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        ((target_type IS NOT NULL AND target_id IS NOT NULL) AND unresolved_target_text IS NULL)
     OR ((target_type IS NULL AND target_id IS NULL) AND unresolved_target_text IS NOT NULL)
    ),
    CHECK (
        target_id IS NULL
     OR NOT (source_type = target_type AND source_id = target_id)
    )
);
CREATE UNIQUE INDEX idx_graph_edge_resolved_live
    ON graph_edge (source_type, source_id, target_type, target_id, kind)
    WHERE target_id IS NOT NULL AND status IN ('confirmed', 'candidate');
CREATE UNIQUE INDEX idx_graph_edge_unresolved_live
    ON graph_edge (source_type, source_id, unresolved_target_text, kind)
    WHERE unresolved_target_text IS NOT NULL AND status IN ('confirmed', 'candidate');
CREATE INDEX idx_graph_edge_forward
    ON graph_edge (source_type, source_id, kind, status);
CREATE INDEX idx_graph_edge_reverse
    ON graph_edge (target_type, target_id, kind, status)
    WHERE target_id IS NOT NULL;
CREATE INDEX idx_graph_edge_candidates
    ON graph_edge (project_id, kind, created_at DESC)
    WHERE status = 'candidate';
