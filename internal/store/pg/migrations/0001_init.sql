-- 3. rag_chunk
-- Re-indexing replaces all chunks for (source_type, source_id) inside a single transaction
-- via DELETE (cascading rag_embedding) followed by inserting fresh chunks and embeddings.
CREATE TABLE rag_chunk (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     BIGINT NOT NULL REFERENCES project(id),
    source_type    TEXT NOT NULL CHECK (source_type IN ('issue', 'activity', 'spec', 'record')),
    source_id      BIGINT NOT NULL,
    artifact_id    BIGINT REFERENCES normalized_artifact(id) ON DELETE CASCADE,
    chunk_index    INTEGER NOT NULL CHECK (chunk_index >= 0),
    section_path   TEXT NOT NULL DEFAULT '',
    header_prefix  TEXT NOT NULL DEFAULT '',
    chunk_text     TEXT NOT NULL,
    search_text    TEXT NOT NULL,
    content_sha256 TEXT NOT NULL,
    archived       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_type, source_id, chunk_index)
);
-- Composite partial PGroonga index for active search chunks without a competing B-tree index.
CREATE INDEX idx_rag_chunk_pgroonga_active
    ON rag_chunk
    USING pgroonga (search_text, project_id)
    WITH (tokenizer='TokenBigram', normalizer='NormalizerAuto')
    WHERE NOT archived;

